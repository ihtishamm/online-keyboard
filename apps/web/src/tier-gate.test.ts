// @vitest-environment node
/**
 * Tier gate and roster (plan §5.4). Works out the tier each language has earned from what
 * exists: page copy, cheat sheets, tutor and typing-test pages, word list, spell check, smart
 * accents (Latin scripts) and Roman evaluation results. Fails when a language.json claims a higher tier, and when
 * LANGUAGES.md (the roster) is out of date:
 *
 *   pnpm roster    # rewrite LANGUAGES.md
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { LANGUAGES, getLayout, type Language, type Tier } from "@okb/layouts";
import { describe, expect, it } from "vitest";
import { allSheets } from "./components/cheatsheet/sheets";
import { accentAccuracyFor, accuracyFor } from "./content/accuracy";

const WEB = process.cwd();
const ROOT = join(WEB, "../..");
const DICTS = join(ROOT, "packages/dictionaries");
const spelling = JSON.parse(readFileSync(join(DICTS, "results/spelling.json"), "utf8")) as Record<
  string,
  { spellcheck: boolean }
>;

interface Check {
  name: string;
  ok: boolean;
}

function checks(l: Language): { C: Check[]; B: Check[]; A: Check[] } {
  const copy = readFileSync(join(WEB, `src/content/languages/${l.slug}.md`), "utf8");
  const faqs = copy.match(/^ {2}- q:/gm)?.length ?? 0;
  const sheets = new Set(allSheets().map((s) => s.layoutId));
  const page = (name: string) => existsSync(join(WEB, `src/pages/${name}.astro`));
  const stats = join(DICTS, `data/${l.code}/stats.json`);
  const words = existsSync(stats)
    ? (JSON.parse(readFileSync(stats, "utf8")) as { wordsKept: number }).wordsKept
    : 0;
  const roman = l.layouts.map(getLayout).find((x) => x.translit)?.translit;
  return {
    C: [
      { name: "layouts", ok: l.layouts.length > 0 },
      { name: "cheat sheet for every layout", ok: l.layouts.every((id) => sheets.has(id)) },
      { name: "at least 4 FAQs", ok: faqs >= 4 },
      { name: "typing tutor", ok: page(`${l.slug}-typing-tutor`) },
    ],
    B: [
      { name: "word list of 20k+ words", ok: l.wordList && words >= 20_000 },
      { name: "spell check meets its targets", ok: spelling[l.code]?.spellcheck ?? false },
      { name: "Roman typing evaluated", ok: !roman || accuracyFor(roman) !== undefined },
      {
        name: "smart accents meet their target",
        ok: l.script !== "Latn" || (accentAccuracyFor(l.code)?.meetsTarget ?? false),
      },
      { name: "typing test", ok: page(`${l.slug}-typing-test`) },
    ],
    // Native-speaker review and the held-out message test need evidence we do not have yet.
    A: [{ name: "native-speaker review", ok: false }],
  };
}

export function earnedTier(l: Language): Tier {
  const c = checks(l);
  const pass = (xs: Check[]) => xs.every((x) => x.ok);
  if (!pass(c.C)) return null;
  if (!pass(c.B)) return "C";
  return pass(c.A) ? "A" : "B";
}

const RANK = { A: 3, B: 2, C: 1 } as const;
const rank = (t: Tier) => (t ? RANK[t] : 0);

export function roster(): string {
  const rows = LANGUAGES.map((l) => {
    const c = checks(l);
    const earned = earnedTier(l);
    const next = earned === "B" ? c.A : earned === "C" ? c.B : earned === null ? c.C : [];
    const missing = next.filter((x) => !x.ok).map((x) => x.name);
    const roman = l.layouts.map(getLayout).find((x) => x.translit)?.translit;
    const acc = roman ? accuracyFor(roman) : undefined;
    return [
      `${l.name.en} (/${l.slug})`,
      l.script,
      earned ?? "–",
      l.wordList ? "yes" : "no",
      spelling[l.code]?.spellcheck ? "yes" : l.wordList ? "Beta" : "no",
      acc ? `${Math.round(acc.top1 * 1000) / 10} %${acc.beta ? " (Beta)" : ""}` : "–",
      l.voice.length ? l.voice.join(", ") : "no",
      missing.join("; ") || "–",
    ];
  });
  const head = ["Language", "Script", "Tier", "Word list", "Spell check", "Roman top-1", "Voice"];
  head.push("Missing for the next tier");
  return [
    "# Languages",
    "",
    "Generated by `pnpm roster` (apps/web/src/tier-gate.test.ts) from the language registry",
    "and the evaluation results. Do not edit by hand. Tiers are defined in plan.md §5.4.",
    "",
    `| ${head.join(" | ")} |`,
    `|${head.map(() => "---").join("|")}|`,
    ...rows.map((r) => `| ${r.join(" | ")} |`),
    "",
  ].join("\n");
}

describe("tier gate", () => {
  it.each(LANGUAGES.map((l) => [l.slug, l] as const))("%s claims no more than it has", (_, l) => {
    expect(rank(l.tier)).toBeLessThanOrEqual(rank(earnedTier(l)));
  });

  it("LANGUAGES.md is up to date (run pnpm roster)", () => {
    const file = join(ROOT, "LANGUAGES.md");
    if (process.env.ROSTER_WRITE === "1") writeFileSync(file, roster());
    expect(existsSync(file) ? readFileSync(file, "utf8") : "").toBe(roster());
  });
});
