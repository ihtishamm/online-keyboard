/** Letters f (short i) moves past, and letters a reph sits on, as HinLegacy lists them. */
const PRE_CLASS =
  "\u0915\u0916\u0917\u0918\u0919\u091A\u091B\u091C\u091D\u091E\u091F\u0920\u0921\u0921\u093C\u0922\u0922\u093C\u0923\u0924\u0925\u0926\u0927\u0928\u092A\u092B\u092C\u092D\u092E\u092F\u0930\u0932\u0935\u0936\u0937\u0938\u0939\u0915\u094D\u0937";
const REPH_CLASS =
  "\u0915\u0916\u0917\u0918\u091A\u091B\u091C\u091D\u091F\u0920\u0921\u0921\u093C\u0922\u0922\u093C\u0923\u0924\u0925\u0926\u0927\u0928\u092A\u092B\u092C\u092D\u092E\u092F\u0930\u0932\u0933\u0935\u0936\u0937\u0938\u0939\u0915\u094D\u0937\u091C\u094D\u091E";

export function hinlegacyDecode(input: string): string {
  let s = input.replace(/([ZzsSqwa\u00A1`]+)Q/g, "Q$1");
  for (const [from, to] of PAIRS) {
    while (s.includes(from)) s = s.split(from).join(to);
  }
  s = s.replace(/([\u0947\u0948\u0941\u0942\u0902]+)\u094D\u0930/g, "\u094D\u0930$1");
  s = s.replace(/\u0902([\u093E\u0947\u0948\u0941\u0942]+)/g, "$1\u0902");
  s = s.replace(/([ \n])\u093E/g, "$1\u0936");
  s = s.split("\u00AF").join("f").split("\u0141").join("\u0930\u094Df");
  s = s.replace(new RegExp(`([f\u017B])([${PRE_CLASS}])`, "g"), "$2$1");
  for (let i = 0; i < 2; i++) {
    s = s.replace(new RegExp(`([f\u017B])(\u094D)([${PRE_CLASS}])`, "g"), "$2$3$1");
  }
  s = s.split("f").join("\u093F").split("\u017B").join("\u093F\u0902");
  s = s.split("\u00B1").join("Z\u0902");
  s = s.replace(
    new RegExp(
      `([${REPH_CLASS}])([\u093E\u093F\u0940\u0941\u0942\u0943\u0947\u0948\u094B\u094C\u0902\u0901]*)(Z)`,
      "g",
    ),
    "$3$1$2",
  );
  s = s.replace(new RegExp(`([${REPH_CLASS}])(\u094D)(Z)`, "g"), "$3$1$2");
  return s.split("Z").join("\u0930\u094D");
}
