function replaceEach(text: string, pairs: [string, string][]): string {
  for (const [from, to] of pairs) text = text.split(from).join(to);
  return text;
}

export function classicDecode(input: string): string {
  let s = replaceEach(input, DECODE);
  s = s.replace(/±/g, "Zं").replace(/Æ/g, "र्f");
  let p = s.indexOf("f");
  while (p !== -1) {
    const next = s.charAt(p + 1);
    s = s.replace("f" + next, next + "ि");
    p = s.indexOf("f", p + 1);
  }
  s = s.replace(/Ç/g, "fa").replace(/É/g, "र्fa");
  p = s.indexOf("fa");
  while (p !== -1) {
    const next = s.charAt(p + 2);
    s = s.replace("fa" + next, next + "िं");
    p = s.indexOf("fa", p + 2);
  }
  s = s.replace(/Ê/g, "ीZ");
  p = s.indexOf("ि्");
  while (p !== -1) {
    const next = s.charAt(p + 2);
    s = s.replace("ि्" + next, "\u094D" + next + "ि");
    p = s.indexOf("ि्", p + 2);
  }
  const matras =
    "अ आ इ ई उ ऊ ए ऐ ओ औ ा ि ी \u0941 \u0942 \u0943 \u0947 \u0948 ो ौ \u0902 : \u0901 \u0945";
  p = s.indexOf("Z");
  while (p > 0) {
    let q = p - 1;
    while (q >= 0 && matras.includes(s.charAt(q)) && s.charAt(q) !== " ") q--;
    const part = s.substr(q, p - q);
    s = s.replace(part + "Z", "र्" + part);
    p = s.indexOf("Z");
  }
  return s;
}

/** The classic Unicode → Kruti Dev steps: ि and reph moves, then the table. */
export function classicEncode(input: string): string {
  let s = input.normalize("NFD");
  let p = s.indexOf("ि");
  while (p !== -1) {
    const left = s.charAt(p - 1);
    s = s.replace(left + "ि", "f" + left);
    p = p - 1;
    while (s.charAt(p - 1) === "\u094D" && p !== 0) {
      const half = s.charAt(p - 2) + "\u094D";
      s = s.replace(half + "f", "f" + half);
      p = p - 2;
    }
    p = s.indexOf("ि");
  }
  const matras = "ािीुूृेैोौं:\u0901\u0945";
  s += "  ";
  p = s.indexOf("र्");
  while (p > 0) {
    let z = p + 2;
    while (matras.indexOf(s.charAt(z + 1)) !== -1 && s.charAt(z + 1) !== "") z++;
    const part = s.substr(p + 2, z - p - 1);
    s = s.replace("र्" + part, part + "Z");
    p = s.indexOf("र्");
  }
  return replaceEach(s.slice(0, -2), ENCODE);
}
