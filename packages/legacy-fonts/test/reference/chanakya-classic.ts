const MATRAS =
  "\u093E \u093F \u0940 \u0941 \u0942 \u0943 \u0947 \u0948 \u094B \u094C \u0902 \u0903 \u0901 \u0945";

export function classicDecode(input: string): string {
  let s = input;
  for (const [from, to] of DECODE) {
    while (s.includes(from)) s = s.replace(from, to);
  }
  s = s.replace(/Z/g, "\u00FC\u0902");
  // \u00E7 (short i) moves past one letter, then past each virama + letter after it.
  let p = s.indexOf("\u00E7");
  while (p !== -1) {
    const next = s.charAt(p + 1);
    s = s.replace("\u00E7" + next, next + "\u093F");
    p += 1;
    while (s.charAt(p + 1) === "\u094D" && p < s.length - 1) {
      const pair = s.charAt(p + 1) + s.charAt(p + 2);
      s = s.replace("\u093F" + pair, pair + "\u093F");
      p += 2;
    }
    p = s.indexOf("\u00E7", p + 1);
  }
  // \u00FC (reph) moves back over the signs and one letter.
  p = s.indexOf("\u00FC");
  while (p > 0) {
    let q = p - 1;
    while (MATRAS.includes(s.charAt(q)) && s.charAt(q) !== " ") q--;
    const part = s.substr(q, p - q);
    s = s.replace(part + "\u00FC", "\u0930\u094D" + part);
    p = s.indexOf("\u00FC");
  }
  return s;
}
