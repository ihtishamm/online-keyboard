/**
 * Writes src/registry.ts from languages/<slug>/: each language.json, its layout files and
 * the transliteration schemes its layouts name (plan item 7.1). Static imports keep the
 * registry usable anywhere TypeScript runs and let bundlers drop what a page does not use.
 *
 *   node scripts/registry.ts        # after adding or changing a language
 *
 * test/registry.test.ts fails while src/registry.ts is out of date.
 */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";

const ROOT = new URL("../", import.meta.url);

interface Entry {
  slug: string;
  order: number;
  layouts: string[];
}

/** Valid identifier from a slug or id: "ur-phonetic" -> "urPhonetic". */
const ident = (s: string) => s.replace(/-(\w)/g, (_, c: string) => c.toUpperCase());
/** Scheme export name: "ur-roman" -> "UR_ROMAN". */
const schemeExport = (id: string) => id.toUpperCase().replace(/-/g, "_");

export function generateRegistry(): string {
  const dir = new URL("languages/", ROOT);
  const entries = readdirSync(dir)
    .map((slug) => JSON.parse(readFileSync(new URL(`${slug}/language.json`, dir), "utf8")) as Entry)
    .sort((a, b) => a.order - b.order);

  const imports: string[] = [];
  const languages: string[] = [];
  const layouts: string[] = [];
  const schemes: string[] = [];
  for (const { slug, layouts: ids } of entries) {
    imports.push(`import ${ident(slug)} from "../languages/${slug}/language.json";`);
    languages.push(ident(slug));
    for (const id of ids) {
      const file = id.slice(id.indexOf("-") + 1);
      const raw = JSON.parse(readFileSync(new URL(`${slug}/${file}.json`, dir), "utf8")) as {
        id: string;
        translit?: string;
      };
      if (raw.id !== id)
        throw new Error(`languages/${slug}/${file}.json has id "${raw.id}", not "${id}"`);
      imports.push(`import ${ident(id)} from "../languages/${slug}/${file}.json";`);
      layouts.push(ident(id));
      if (raw.translit) {
        imports.push(`import { ${schemeExport(raw.translit)} } from "./translit/${raw.translit}";`);
        schemes.push(schemeExport(raw.translit));
      }
    }
  }
  const list = (xs: string[]) => xs.map((x) => `  ${x},`).join("\n");
  return `// Generated by scripts/registry.ts from languages/<slug>/: do not edit by hand.
import type { TranslitScheme } from "@okb/engine";
import type { LayoutInput } from "@okb/engine/layout";
import type { LanguageFile } from "./language";
${imports.join("\n")}

/** Every language.json, in page order. */
export const LANGUAGE_FILES = [
${list(languages)}
] as LanguageFile[];

/** Every layout file, by language, in each language's order. */
export const RAW_LAYOUTS = [
${list(layouts)}
] as LayoutInput[];

/** The transliteration schemes the layouts use. */
export const SCHEME_LIST: readonly TranslitScheme[] = [
${list(schemes)}
];

export {
${list(schemes)}
};
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync(new URL("src/registry.ts", ROOT), generateRegistry());
  console.log("wrote src/registry.ts");
}
