/**
 * The import report (IMPORTS.md): for every layout built from vendor/, its source, licence,
 * coverage, what the importer skipped and what we changed. test/imported.test.ts keeps it fresh;
 * UPDATE_LAYOUTS=1 rewrites it.
 */
import { readFileSync, readdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { importCldr, importKeyman, importXkb, type KeyCode, type KeyDef } from "@okb/engine/layout";
import { IMPORTS, buildImport, type ImportSpec } from "./imports";

const LAYERS = ["n", "s", "ag", "sag"] as const;

function licence(vendor: string, spec: ImportSpec["from"]): string {
  if ("cldr" in spec) return "Unicode License v3 (vendor/cldr/LICENSE)";
  if ("xkb" in spec) return "X11/MIT-style (vendor/xkb/LICENSE)";
  const dir = join(vendor, dirname(spec.keyman));
  const file = readdirSync(dir).find((f) => /^LICEN[CS]E/i.test(f));
  if (!file) return "**no licence file**";
  const text = readFileSync(join(dir, file), "utf8");
  const kind = /MIT License/i.test(text) ? "MIT" : "see file";
  const holder = /Copyright\s+(?:©|\(c\))\s*[\d-]+\s+(.+)/i.exec(text)?.[1]?.trim();
  return `${kind}${holder ? `, ${holder}` : ""} (vendor/${dirname(spec.keyman)}/${file})`;
}

/** Characters on each layer, and dead-key compositions. */
function coverage(keys: Partial<Record<KeyCode, KeyDef>>, deadkeys: number, rules = 0): string {
  const counts = LAYERS.map((l) => [l, Object.values(keys).filter((d) => d?.[l]).length] as const)
    .filter(([, n]) => n > 0)
    .map(([l, n]) => `${l} ${n}`);
  return `${Object.keys(keys).length} keys (${counts.join(", ")})${deadkeys ? `, ${deadkeys} dead-key compositions` : ""}${rules ? `, ${rules} context rules` : ""}`;
}

/** Keys our patch changed, as `Code.layer: before → after`. */
function changes(spec: ImportSpec, source: string): string[] {
  if (!spec.patch && !spec.patchRules) return [];
  const raw =
    "cldr" in spec.from
      ? importCldr(source).keys
      : "xkb" in spec.from
        ? importXkb(source, spec.from.variant).keys
        : importKeyman(source, spec.from).keys;
  const patched = buildImport(spec, source).layout.keys ?? {};
  const out: string[] = [];
  const codes = new Set([...Object.keys(raw), ...Object.keys(patched)] as KeyCode[]);
  for (const code of codes) {
    for (const layer of LAYERS) {
      const before = raw[code]?.[layer]?.normalize("NFC");
      const after = patched[code]?.[layer];
      if (before !== after) out.push(`${code}.${layer}: ${show(before)} → ${show(after)}`);
    }
  }
  if (spec.patchRules && "keyman" in spec.from) {
    const before = importKeyman(source, spec.from).rules;
    const after = buildImport(spec, source).layout.rules ?? [];
    const text = (r: (typeof before)[number]) =>
      `${show(r.before)} + ${show(r.typed)}${r.remove ? ` removes ${r.remove},` : ""} adds ${show(r.add)}${r.hold ? " and holds" : ""}`;
    if (before.length === after.length) {
      before.forEach((r, i) => {
        const was = text(r);
        const now = after[i] ? text(after[i]!) : "none";
        if (was !== now) out.push(`Rule: ${was} → ${now}`);
      });
    } else {
      // A filtered table: the layout's `source` says what was left out.
      out.push(`Rules: ${before.length} upstream → ${after.length} here`);
    }
  }
  return out;
}

const show = (s: string | undefined) =>
  s === undefined
    ? "none"
    : `\`${[...s].map((c) => (/[\p{M}\p{Cf}]/u.test(c) ? `U+${c.codePointAt(0)!.toString(16).toUpperCase().padStart(4, "0")}` : c)).join("")}\``;

const cell = (s: string) => s.replace(/\|/g, "\\|").replace(/\n/g, " ");

export function importReport(root: string): string {
  const vendor = join(root, "vendor");
  const lines = [
    "# Imported layouts",
    "",
    "Generated by `scripts/import-report.ts` (`pnpm --filter @okb/layouts import:layouts`). Do not edit.",
    "",
    "Every layout here is built from a file in `vendor/` and checked against it by `test/imported.test.ts`.",
    "Rules the importers cannot express are listed under **Skipped** and left out, never imported wrongly.",
    "",
  ];
  for (const spec of IMPORTS) {
    const path =
      "cldr" in spec.from ? spec.from.cldr : "xkb" in spec.from ? spec.from.xkb : spec.from.keyman;
    const source = readFileSync(join(vendor, path), "utf8");
    const { layout, warnings } = buildImport(spec, source);
    const changed = changes(spec, source);
    lines.push(
      `## ${spec.meta.id}`,
      "",
      `- **Output:** \`languages/${spec.out}\``,
      `- **Source:** \`vendor/${path}\`. ${cell(spec.meta.source ?? "")}`,
      `- **Licence:** ${licence(vendor, spec.from)}`,
      `- **Coverage:** ${coverage(layout.keys ?? {}, layout.deadkeys?.length ?? 0, layout.rules?.length ?? 0)}`,
      `- **Skipped:** ${warnings.length ? "" : "nothing"}`,
      ...warnings.map((w) => `  - ${cell(w)}`),
      `- **Our changes:** ${changed.length ? "" : "none"}`,
      ...changed.map((c) => `  - ${c}`),
      "",
    );
  }

  const used = new Set(IMPORTS.map((s) => ("cldr" in s.from ? s.from.cldr : "")));
  const spare = readdirSync(join(vendor, "cldr"))
    .filter((f) => f.endsWith(".xml") && !used.has(`cldr/${f}`))
    .sort();
  lines.push(
    "## Vendored, not yet used",
    "",
    "CLDR 43 Windows keyboards ready for the national layouts (plan 7.5). Unicode License v3.",
    "",
    "| File | Name | Coverage | Skipped |",
    "| --- | --- | --- | --- |",
  );
  for (const f of spare) {
    const r = importCldr(readFileSync(join(vendor, "cldr", f), "utf8"));
    lines.push(
      `| \`${f}\` | ${r.name ?? ""} | ${coverage(r.keys, r.deadkeys.length)} | ${r.warnings.length ? cell(r.warnings.join("; ")) : "nothing"} |`,
    );
  }

  lines.push(
    "",
    "## xkeyboard-config (evaluated, not used)",
    "",
    "The X11 layouts (xkeyboard-config 2.41) are under permissive MIT and HPND-style notices, listed in the",
    "project's `COPYING`. Most `symbols/` files carry no notice of their own (fr, de, es, tr, pl, us …);",
    "a few do (hu has its own permission notice). So the project `COPYING` would have to ship with any",
    "file we import, and each file's header is checked before it is vendored. Every layout we need today",
    "is in CLDR, so there is no X11 importer yet. It is the fallback for layouts CLDR and Keyman lack.",
    "",
  );
  return lines.join("\n");
}
