"""Writes src/number-words-data.ts: the words for 0 to 99 and the scale words (hundred to
kharab) in Urdu, Hindi and Bangla, from CLDR's spell-out rules (Unicode License).

    python3 -I scripts/make-number-words.py DIR

DIR holds ur.xml, hi.xml and bn.xml from
https://github.com/unicode-org/cldr/tree/main/common/rbnf (fetched 2026-11-07).
"""

import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
src = pathlib.Path(sys.argv[1])
SCALES = {"100": "hundred", "1000": "thousand", "100000": "lakh", "10000000": "crore", "1000000000": "arab", "100000000000": "kharab"}
out = [
    "/**",
    " * Number words for Urdu, Hindi and Bangla: 0 to 99 and the scale words, from CLDR's",
    " * spell-out rules (common/rbnf, main branch, fetched 2026-11-07; © Unicode, Inc., Unicode",
    " * License v3). Generated by scripts/make-number-words.py; do not edit by hand.",
    " */",
    "",
    "export interface SouthAsianWords {",
    "  /** 0 to 99. */",
    "  units: readonly string[];",
    "  hundred: string;",
    "  /** True when the hundred word is joined to the number before it (Bangla একশো). */",
    "  hundredJoined: boolean;",
    "  thousand: string;",
    "  lakh: string;",
    "  crore: string;",
    "  arab: string;",
    "  kharab: string;",
    "}",
    "",
]
for code in ["ur", "hi", "bn"]:
    xml = (src / f"{code}.xml").read_text("utf-8")
    cdata = re.search(r'type="SpelloutRules">\s*<rbnfRules><!\[CDATA\[(.*?)\]\]>', xml, re.S).group(1)
    card = cdata.split("%spellout-cardinal:")[1].split("\n%")[0]
    units = {}
    for m in re.finditer(r"^(\d+): ([^;<>=\[\]]+);$", card, re.M):
        if int(m.group(1)) < 100:
            units[int(m.group(1))] = m.group(2)
    assert sorted(units) == list(range(100)), code
    scale = {}
    joined = False
    for m in re.finditer(r"^(\d+): <<( ?)([^\[ ]+)\[ >>\];$", card, re.M):
        if m.group(1) in SCALES:
            scale[SCALES[m.group(1)]] = m.group(3)
            if m.group(1) == "100":
                joined = m.group(2) == ""
    assert len(scale) == 6, (code, scale)
    out.append(f"export const {code.upper()}: SouthAsianWords = {{")
    out.append(f"  units: {json.dumps([units[i] for i in range(100)], ensure_ascii=False)},")
    for k in ["hundred"]:
        out.append(f"  {k}: {json.dumps(scale[k], ensure_ascii=False)},")
    out.append(f"  hundredJoined: {'true' if joined else 'false'},")
    for k in ["thousand", "lakh", "crore", "arab", "kharab"]:
        out.append(f"  {k}: {json.dumps(scale[k], ensure_ascii=False)},")
    out.append("};")
    out.append("")
(ROOT / "src/number-words-data.ts").write_text("\n".join(out), "utf-8")
print("written")
